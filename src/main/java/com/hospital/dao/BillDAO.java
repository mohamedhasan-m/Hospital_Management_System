package com.hospital.dao;

import com.hospital.model.Bill;
import com.hospital.util.DBUtil;

import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.ArrayList;
import java.util.List;

/** Database access for the bills table (all queries use PreparedStatement). */
public class BillDAO {

    public List<Bill> findAll() throws SQLException {
        String sql = "SELECT b.id, b.patient_id, p.name AS patient_name, b.consultation_fee, "
                + "b.medicine_charges, b.room_charges, b.other_charges, b.total_amount, b.bill_date "
                + "FROM bills b JOIN patients p ON b.patient_id = p.id "
                + "ORDER BY b.id DESC";
        List<Bill> list = new ArrayList<>();

        try (Connection con = DBUtil.getConnection();
             PreparedStatement ps = con.prepareStatement(sql);
             ResultSet rs = ps.executeQuery()) {

            while (rs.next()) {
                Bill b = new Bill();
                b.setId(rs.getInt("id"));
                b.setPatientId(rs.getInt("patient_id"));
                b.setPatientName(rs.getString("patient_name"));
                b.setConsultationFee(rs.getDouble("consultation_fee"));
                b.setMedicineCharges(rs.getDouble("medicine_charges"));
                b.setRoomCharges(rs.getDouble("room_charges"));
                b.setOtherCharges(rs.getDouble("other_charges"));
                b.setTotalAmount(rs.getDouble("total_amount"));
                b.setBillDate(rs.getString("bill_date").substring(0, 10));   // keep only yyyy-MM-dd
                list.add(b);
            }
        }
        return list;
    }

    /** Saves the bill and returns the new bill number generated by MySQL (AUTO_INCREMENT). */
    public int insert(Bill b) throws SQLException {
        String sql = "INSERT INTO bills (patient_id, consultation_fee, medicine_charges, room_charges, other_charges, total_amount) "
                + "VALUES (?, ?, ?, ?, ?, ?)";

        try (Connection con = DBUtil.getConnection();
             PreparedStatement ps = con.prepareStatement(sql, Statement.RETURN_GENERATED_KEYS)) {

            ps.setInt(1, b.getPatientId());
            ps.setDouble(2, b.getConsultationFee());
            ps.setDouble(3, b.getMedicineCharges());
            ps.setDouble(4, b.getRoomCharges());
            ps.setDouble(5, b.getOtherCharges());
            ps.setDouble(6, b.getTotalAmount());
            ps.executeUpdate();

            try (ResultSet keys = ps.getGeneratedKeys()) {
                if (keys.next()) {
                    return keys.getInt(1);
                }
            }
        }
        return 0;
    }
}
